    public void mtdInformacionGeneral(){
        lblMesero.setText(this.venta.getUsuarios().getNombres()+" "+this.venta.getUsuarios().getApellidos());
        lblUbicacion.setText(this.venta.getMesas().getTipo()+" "+this.venta.getMesas().getNumero());
        lblValorTotal.setText(String.valueOf(NumberFormat.getCurrencyInstance(new Locale("es", "CO")).format(this.venta.getTotal())));
        lblPedidos.setText(String.valueOf(this.venta.getPedidoses().size()));
        lblTotalVenta.setText(String.valueOf(NumberFormat.getCurrencyInstance(new Locale("es", "CO")).format(this.venta.getTotal())));
        lblSubtotal.setText(String.valueOf(NumberFormat.getCurrencyInstance(new Locale("es", "CO")).format(this.venta.getTotal())));
    }
    
    public void mtdCargarPedidos(){
        
        
          
        
        for (Object pedidos: this.venta.getPedidoses()) {
            Pedidos dataPedido = (Pedidos) pedidos;
            
            frmDetallePedido formDetallePedido = new frmDetallePedido(this);
            formDetallePedido.mtdUbicarInformacion(dataPedido);
           
           PanelPedidos.add(formDetallePedido);
           PanelPedidos.revalidate();
           PanelPedidos.repaint();
            
        }
        
    }
   


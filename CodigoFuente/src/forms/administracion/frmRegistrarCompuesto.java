    private void btnDeleteSubProductoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteSubProductoActionPerformed
        
        int fila = tblSubproductos.getSelectedRow();
        
        if(fila != -1){
            
            models.Subproductos subp = (models.Subproductos) tblSubproductos.getValueAt(fila, 0);
            
           String vl = String.valueOf(tblSubproductos.getValueAt(fila, 3));
            
            totalCosto = totalCosto - Integer.parseInt(vl);
            
            lblTotalCosto.setText(String.valueOf(NumberFormat.getCurrencyInstance(new Locale("es", "CO")).format(totalCosto)));
            txtCosto.setText(String.valueOf(totalCosto));
            
            ArraySubProductos.remove(subp);
            
            DefaultTableModel mod = (DefaultTableModel) tblSubproductos.getModel();
            mod.removeRow(fila);
            
        }else{
            JOptionPane.showMessageDialog(rootPane, "Seleccione un Producto","Infomración",JOptionPane.INFORMATION_MESSAGE);
        }

        // TODO add your handling code here:
    }//GEN-LAST:event_btnDeleteSubProductoActionPerformed


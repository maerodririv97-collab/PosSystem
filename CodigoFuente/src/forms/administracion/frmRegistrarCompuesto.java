    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        
        subProducto = new models.Subproductos();
        
        models.Productos subPro = (models.Productos) cmbProductos.getSelectedItem();
        models.Productos dataSubProducto = (models.Productos) subPro;
        
        subProducto.setProductosBySubproducto(subPro);
        subProducto.setCantidad(BigDecimal.valueOf(Double.parseDouble(txtCantidad.getText())));
        
        ArraySubProductos.add(subProducto);
        
        
        
        DefaultTableModel df = (DefaultTableModel) tblSubproductos.getModel();
        int valor =0;
       if(dataSubProducto.getTipoVenta().equalsIgnoreCase("Peso")){
          
            BigDecimal stockSub = dataSubProducto.getStock();
             int stoPromo = stockSub.setScale(0, RoundingMode.DOWN).intValueExact();
             
             int valorXMl = dataSubProducto.getCosto() / stoPromo;
          
             valor = valorXMl * Integer.parseInt(txtCantidad.getText());
             
           
       }else{
         valor = dataSubProducto.getCosto() * Integer.parseInt(txtCantidad.getText());
        }
        totalCosto +=  valor;
        
        
        df.addRow(new Object[]{subProducto,dataSubProducto.getNombre(),Double.parseDouble(txtCantidad.getText()),valor });
        
        tblSubproductos.setModel(df);
        
       lblTotalCosto.setText(String.valueOf(NumberFormat.getCurrencyInstance(new Locale("es", "CO")).format(totalCosto)));
       txtCosto.setText(String.valueOf(totalCosto));
       txtCantidad.setText("");
        
        

        // TODO add your handling code here:
    }//GEN-LAST:event_btnAddActionPerformed

